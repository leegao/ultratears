def generate_auto_stubs_c(
    stubs: list[CalleeClassification],
    sample_ll_path: Path,
    fn_names: list[str],
    solved_params: list[tuple[SolvedFunctionPathParams, SolvedFunctionPathParams]],
    out_path: Path,
):
    """Synthesizes self-contained C runtime stubs including stub_apply_path_params."""
    lines = [
        "// AUTOGENERATED by ultrs stub_analyzer.py - DO NOT EDIT MANUALLY",
        "// Synthesized C Runtime Stubs for Horizon / Game Subroutines",
        "#include <stdint.h>",
        "#include <string.h>",
        "#include <stdlib.h>",
        "",
        "typedef struct {",
        "    uint64_t x[31];",
        "    uint64_t sp;",
        "    uint64_t pc;",
        "    uint32_t nzcv;",
        "    uint32_t fpcr;",
        "    uint32_t fpsr;",
        "    uint32_t padding;",
        "    uint64_t tpidr;",
        "    uint64_t tpidrro;",
        "    __uint128_t v[32];",
        "} Cpu;",
        "",
        "volatile int g_fnprof = 0;",
        "uint64_t g_icache_pc[65536];",
        "void* g_icache_fn[65536];",
        "",
        "uint64_t g_stub_heap_ptr = 0x804000100ULL;",
        "uint64_t g_stub_heap_end = 0x804200000ULL;",
        "uint64_t g_stub_call_count = 0;",
        "int g_bench_mode = 0;",
        "uint32_t g_stub_branch_policy = 0;",
        "uint64_t g_stub_trace_hash = 0xCBF29CE484222325ULL;",
        "uint32_t g_stub_rng_state = 0x12345678u;",
        "",
        "void stub_set_bench_mode(int mode) { g_bench_mode = mode; }",
        "void stub_set_branch_policy(uint32_t policy) { g_stub_branch_policy = policy; }",
        "void stub_reset_state(uint32_t seed) {",
        "    if (g_icache_pc[0] == 0) memset(g_icache_pc, 0xFF, sizeof(g_icache_pc));",
        "    g_stub_call_count = 0;",
        "    g_stub_heap_ptr = 0x804000100ULL;",
        "    g_stub_trace_hash = 0xCBF29CE484222325ULL;",
        "    g_stub_rng_state = seed ? seed : 0x12345678u;",
        "}",
        "uint64_t stub_get_trace_hash(void) { return g_stub_trace_hash; }",
        "uint64_t stub_get_call_count(void) { return g_stub_call_count; }",
        "uint64_t stub_get_heap_ptr(void)   { return g_stub_heap_ptr; }",
        "",
        "// Constraint-Solved Entry Register, Guest Memory & Branch Policy Initializer",
        "// path_mode = 0 -> Maximal Finite Path (Longest DAG Path)",
        "// path_mode = 1 -> Representative Common Path (Expected DAG Path)",
        "void stub_apply_path_params(Cpu* c, int path_mode, uint64_t fbase) {",
        "    if (!c || fbase < 0x800000000ULL) return;",
    ]

    if solved_params:
        long_p, comm_p = max(solved_params, key=lambda pair: (pair[0].num_constraints, pair[0].path_insns))
        lines.append(
            f"    if (path_mode == 0) {{ // Longest Finite Path for {long_p.fn_name} ({long_p.path_insns} ARM64 insns, {long_p.num_blocks} BBs)"
        )
        lines.extend(long_p.c_statements)
        lines.append(
            f"    }} else {{ // Common Path for {comm_p.fn_name} ({comm_p.path_insns} ARM64 insns, {comm_p.num_blocks} BBs)"
        )
        lines.extend(comm_p.c_statements)
        lines.append("    }")
    else:
        lines.append("    (void)path_mode;")
    lines.append("}\n")

    lines += [
        "static inline void clobber_caller_saved(Cpu* c, uint64_t tag, int args) {",
        "    (void)args;",
        "    g_stub_call_count++;",
        "    if (g_bench_mode) return;",
        "    g_stub_trace_hash = (g_stub_trace_hash ^ tag ^ c->x[0]) * 0x100000001B3ULL;",
        "    for (int r = 1; r <= 17; ++r) c->x[r] ^= (tag + r);",
        "}\n",
        "static uint64_t guest_alloc(uint64_t sz) {",
        "    sz = (sz + 15ULL) & ~15ULL;",
        "    if (g_stub_heap_ptr + sz > g_stub_heap_end) return 0x803954000ULL;",
        "    uint64_t p = g_stub_heap_ptr; g_stub_heap_ptr += sz;",
        "    uint64_t* q = (uint64_t*)p;",
        "    for (uint64_t i = 0; i < sz / 8; ++i) q[i] = 0x803954000ULL;",
        "    return p;",
        "}\n",
        "void fnprof_hit(uint64_t a, uint64_t b, uint64_t c) { (void)a; (void)b; (void)c; }",
        "void rt_dispatch(Cpu* c) { c->x[0] = guest_alloc(64); }",
        "void rt_svc(Cpu* c, uint32_t imm, uint64_t pc) { (void)c; (void)imm; (void)pc; }",
        "void rt_brk(Cpu* c, uint32_t imm, uint64_t pc) { (void)c; (void)imm; (void)pc; abort(); }",
        "void rt_udf(Cpu* c, uint64_t pc) { (void)c; (void)pc; abort(); }",
        "uint64_t rt_ticks(void) { return 1000ULL + g_stub_call_count; }",
        "int32_t totk_drs_enabled(void) { return 0; }\n",
    ]

    for s in stubs:
        lines.append(f"// [{s.kind.value}] {s.sym_name}: {s.reason}")
        lines.append(f"void {s.sym_name}(Cpu* c) {{")
        tag = f"0x{s.target_pc:x}ULL" if s.target_pc else "0xABCDEF00ULL"
        if s.kind == StubKind.MEMORY_COPY:
            lines.append("    uint64_t dst = c->x[0], src = c->x[1], len = c->x[2] & 0xFFFFFFFFULL;")
            lines.append("    if (dst >= 0x800000000ULL && dst + len <= 0x810000000ULL &&")
            lines.append("        src >= 0x800000000ULL && src + len <= 0x810000000ULL && len <= 4096ULL) {")
            lines.append("        memcpy((void*)(uintptr_t)dst, (const void*)(uintptr_t)src, (size_t)len);")
            lines.append("    }")
            lines.append(f"    clobber_caller_saved(c, {tag}, {s.num_args_read});")
            lines.append("    c->x[0] = dst;")
        elif s.kind == StubKind.POINTER_ALLOC:
            lines.append(f"    clobber_caller_saved(c, {tag}, {s.num_args_read});")
            lines.append("    c->x[0] = guest_alloc(128);")
        elif s.kind == StubKind.BRANCH_SENSITIVE:
            lines.append(f"    clobber_caller_saved(c, {tag}, {s.num_args_read});")
            mask = f"0x{1 << s.policy_bit:x}u" if s.policy_bit >= 0 else "0x1u"
            l_ret_s = "guest_alloc(128)" if (s.returns_ptr_on_nonzero and s.longest_path_ret != 0) else f"0x{s.longest_path_ret:x}ULL"
            a_ret_s = "guest_alloc(128)" if (s.returns_ptr_on_nonzero and s.alt_branch_ret != 0) else f"0x{s.alt_branch_ret:x}ULL"
            lines.append(f"    static uint32_t s_loop_bound_{s.sym_name} = 0;")
            lines.append(f"    if (++s_loop_bound_{s.sym_name} > 100) {{")
            lines.append(f"        c->x[0] = {a_ret_s};")
            lines.append("        return;")
            lines.append("    }")
            lines.append(f"    c->x[0] = (g_stub_branch_policy & {mask}) ? {a_ret_s} : {l_ret_s};")
        else:
            lines.append(f"    clobber_caller_saved(c, {tag}, {s.num_args_read});")
            lines.append("    c->x[0] = 0;")
        lines.append("}\n")

    out_path.write_text("\n".join(lines))


def generate_stub_analysis_md(
    sample_id: str,
    metrics: list[FunctionMetrics],
    fn_cfgs: dict[str, dict[int, CFGBlock]],
    stubs: list[CalleeClassification],
    solved_params: list[tuple[SolvedFunctionPathParams, SolvedFunctionPathParams]],
    out_path: Path,
):
    """Emits comprehensive STUB_ANALYSIS.md documentation."""
    lines = [
        f"# Static Control-Flow & Stub Analysis Report: `{sample_id}`",
        "",
        "## 1. Function Complexity & CFG Topology",
        "",
        "| Function | Entry PC | ARM64 Insns | Basic Blocks | Edges | Has Loops | Longest DAG Path | Common Path | Callees |",
        "| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |",
    ]
    for m in metrics:
        lines.append(
            f"| `{m.name}` | `0x{m.entry_pc:x}` | {m.num_arm64_insns} | {m.num_blocks} | {m.num_edges} | {m.has_loops} | {m.est_longest_path_insns} insns | {m.est_common_path_insns} insns | {m.num_callees} |"
        )
    lines.append("")

    lines += [
        "## 2. External Callee Classification & Stub Strategy",
        "",
        "| Callee Symbol | Target PC | Classification | Args Read | Longest Path Ret | Alt Branch Ret | Policy Bit | Reason |",
        "| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |",
    ]
    for s in stubs:
        t_pc_s = f"`0x{s.target_pc:x}`" if s.target_pc else "Unknown"
        l_ret_s = "guest_alloc(128)" if (s.returns_ptr_on_nonzero and s.longest_path_ret != 0) else f"`0x{s.longest_path_ret:x}`"
        a_ret_s = "guest_alloc(128)" if (s.returns_ptr_on_nonzero and s.alt_branch_ret != 0) else f"`0x{s.alt_branch_ret:x}`"
        p_bit_s = f"Bit {s.policy_bit}" if s.policy_bit >= 0 else "N/A"
        lines.append(
            f"| `{s.sym_name}` | {t_pc_s} | `{s.kind.value}` | {s.num_args_read} | {l_ret_s} | {a_ret_s} | {p_bit_s} | {s.reason} |"
        )
    lines.append("")

    out_path.write_text("\n".join(lines))


def generate_stub_analysis_json(
    sample_id: str,
    metrics: list[FunctionMetrics],
    stubs: list[CalleeClassification],
    solved_params: list[tuple[SolvedFunctionPathParams, SolvedFunctionPathParams]],
    out_path: Path,
):
    """Emits machine-readable stub_analysis.json metadata."""
    data = {
        "sample_id": sample_id,
        "total_arm64_insns": sum(m.num_arm64_insns for m in metrics),
        "total_common_path_insns": sum(m.est_common_path_insns for m in metrics),
        "total_longest_path_insns": sum(m.est_longest_path_insns for m in metrics),
        "functions": [
            {
                "name": m.name,
                "entry_pc": m.entry_pc,
                "static_insns": m.num_arm64_insns,
                "basic_blocks": m.num_blocks,
                "back_edges": 1 if m.has_loops else 0,
                "common_path_insns": m.est_common_path_insns,
                "longest_path_insns": m.est_longest_path_insns,
            }
            for m in metrics
        ],
        "num_branch_sensitive": sum(1 for s in stubs if s.kind == StubKind.BRANCH_SENSITIVE),
        "num_pointer_alloc": sum(1 for s in stubs if s.kind == StubKind.POINTER_ALLOC),
        "num_memory_copy": sum(1 for s in stubs if s.kind == StubKind.MEMORY_COPY),
        "num_constant_zero": sum(1 for s in stubs if s.kind == StubKind.CONSTANT_ZERO),
        "external_stubs": [s.sym_name for s in stubs],
        "callees": [
            {
                "symbol": s.sym_name,
                "target_pc": f"0x{s.target_pc:x}" if s.target_pc else None,
                "kind": s.kind.value,
                "policy_bit": s.policy_bit,
                "reason": s.reason,
            }
            for s in stubs
        ],
    }
    out_path.write_text(json.dumps(data, indent=2))
